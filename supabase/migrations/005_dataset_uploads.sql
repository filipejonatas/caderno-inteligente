-- Upload da planilha pela tela: versões com snapshot (gzip) e versão ativa. Aditiva; rodar depois da 004.
-- Cada versão guarda o conjunto completo (inclusive as linhas de SKUs inativos) e a lista inactive_skus dentro do snapshot.
-- A API guarda as 20 últimas (D7) e nunca remove a ativa.

create table if not exists public.dataset_versions (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_email text not null,
    action text not null check (action in ('upload', 'restore', 'original')),
    filename text,
    file_sha256 text,
    size_bytes integer,
    content_sha256 text not null,
    reference_date date,
    sales_last_month text,
    restored_from bigint,
    summary jsonb not null default '{}'::jsonb,
    snapshot bytea not null
);
create index if not exists dataset_versions_id_desc_idx on public.dataset_versions (id desc);

alter table public.dataset_version add column if not exists active_version_id bigint;

alter table public.dataset_versions enable row level security;

comment on table public.dataset_versions is 'Versões da base aplicadas pela tela (upload, voltar para versão, restaurar original), com snapshot gzip do conjunto.';
comment on column public.dataset_version.active_version_id is 'Versão de dataset_versions que está ativa; nula depois de uma importação pela linha de comando.';
